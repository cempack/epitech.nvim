M.by_code = {}
for _, rule in ipairs(M.rules) do
  M.by_code[rule.code] = rule
end

-- The constructs the coding style lists as unsupported by Banana.
M.extensions = {
  { construct = "__attribute__((noreturn))", replacement = "[[noreturn]]" },
  { construct = "#pragma once", replacement = "#ifndef / #define / #endif" },
  { construct = "\\e", replacement = "\\x1B" },
}

M.severity_rank = { fatal = 1, major = 2, minor = 3, info = 4 }

